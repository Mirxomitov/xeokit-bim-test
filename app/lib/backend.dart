import 'dart:convert';
import 'dart:io';

import 'statuses.dart';

/// A model on the backend (backend/models/`key`.xkt).
class Model {
  Model.fromJson(Map<String, dynamic> json)
      : id = json['id'] as String,
        key = json['key'] as String,
        name = json['name'] as String;

  final String id;

  /// The file name without .xkt, e.g. "arboleda".
  final String key;
  final String name;
}

class StatusSnapshot {
  StatusSnapshot.fromJson(Map<String, dynamic> json)
      : updatedAt = DateTime.parse(json['updatedAt'] as String).toLocal(),
        seeded = json['seeded'] as bool? ?? false,
        statuses = (json['statuses'] as Map<String, dynamic>)
            .map((id, s) => MapEntry(id, ElementStatus.fromWire(s as String?)));

  final DateTime updatedAt;

  /// Test data generated by the server, nobody has changed it yet.
  final bool seeded;
  final Map<String, ElementStatus> statuses;
}

/// backend/ (NestJS): the model list, the .xkt files and the element statuses.
class Backend {
  Backend(this.baseUri);

  final Uri baseUri;
  final _http = HttpClient()..connectionTimeout = const Duration(seconds: 5);

  /// What the viewer in the WebView loads.
  Uri fileUri(Model model) => baseUri.resolve('api/bim/models/${model.id}/file');

  Future<List<Model>> models() async => ((await _getJson('api/bim/models')) as List)
      .map((m) => Model.fromJson(m as Map<String, dynamic>))
      .toList();

  Future<StatusSnapshot> statuses(Model model) async => StatusSnapshot.fromJson(
      await _getJson('api/bim/models/${model.id}/statuses') as Map<String, dynamic>);

  Future<Object?> _getJson(String path) async {
    final request = await _http.getUrl(baseUri.resolve(path));
    final response = await request.close();
    final body = await response.transform(utf8.decoder).join();
    if (response.statusCode != HttpStatus.ok) {
      throw HttpException('${response.statusCode} $body', uri: request.uri);
    }
    return jsonDecode(body);
  }
}
